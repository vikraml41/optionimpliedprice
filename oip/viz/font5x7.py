def draw_text(canvas, text: str, x: int, y: int, rgb, scale: int = 1):
    """Draw ``text`` at top-left (x, y). Returns the x just past the text."""
    cx = x
    for ch in text.upper():
        glyph = _G.get(ch, _G[' '])
        for ry, bits in enumerate(glyph):
            for rx in range(5):
                if bits & (1 << (4 - rx)):
                    for sx in range(scale):
                        for sy in range(scale):
                            canvas.set(cx + rx * scale + sx,
                                       y + ry * scale + sy, rgb)
        cx += 6 * scale
    return cx


def text_width(text: str, scale: int = 1) -> int:
    return len(text) * 6 * scale
